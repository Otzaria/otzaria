import importlib.util
from pathlib import Path
import unittest

SPEC = importlib.util.spec_from_file_location(
    "apple_quiet_changes", Path(__file__).with_name("changes.py"))
changes = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(changes)

WORKFLOW = (Path(__file__).resolve().parents[3] / changes.WORKFLOW).read_text()


def lock(**packages):
    body = "".join(
        f"  {name}:\n    dependency: transitive\n    description:\n"
        f"      name: {name}\n      url: \"https://pub.dev\"\n"
        f"    source: hosted\n    version: \"{version}\"\n"
        for name, version in sorted(packages.items()))
    return f"# Generated by pub\npackages:\n{body}sdks:\n  dart: \">=3.12.0 <4.0.0\"\n"


BASE_LOCK = lock(flutter_inappwebview_ios="1.2.0", sentry_flutter="9.30.1",
                 window_manager="0.5.0", markdown="7.3.0", googleapis="17.0.0")
PUBSPEC = "name: otzaria\ndependencies:\n  markdown: ^7.3.0\nflutter:\n  uses-material-design: true\n"


def decide(files, head_lock=BASE_LOCK, head_pubspec=PUBSPEC):
    base = {"pubspec.lock": BASE_LOCK, "pubspec.yaml": PUBSPEC}
    head = {"pubspec.lock": head_lock, "pubspec.yaml": head_pubspec}
    return changes.decide(set(files), WORKFLOW, base.__getitem__, head.__getitem__)


class TriggerTests(unittest.TestCase):
    def test_pubspec_files_start_the_workflow_for_the_decision_job(self):
        paths = changes.trigger_paths(WORKFLOW)
        self.assertIn("pubspec.lock", paths)
        self.assertIn("pubspec.yaml", paths)
        self.assertIn("lib/plugins/**", paths)

    def test_contracts_only_patterns_are_inside_the_trigger(self):
        paths = changes.trigger_paths(WORKFLOW)
        for pattern in changes.CONTRACTS_ONLY:
            if "*" not in pattern:
                with self.subTest(pattern=pattern):
                    self.assertTrue(any(changes.glob_matches(p, pattern) for p in paths))
        tests = [p for p in paths if p.startswith("test/")]
        self.assertTrue(tests)
        self.assertTrue(all(changes.glob_matches("test/**", p) for p in tests))

    def test_glob_semantics(self):
        self.assertTrue(changes.glob_matches("lib/plugins/**", "lib/plugins/view/a.dart"))
        self.assertFalse(changes.glob_matches("lib/plugins/**", "lib/pluginsx/a.dart"))
        self.assertTrue(changes.glob_matches("a/*.py", "a/b.py"))
        self.assertFalse(changes.glob_matches("a/*.py", "a/b/c.py"))


class DecisionTests(unittest.TestCase):
    def test_probe_and_app_files_run_every_job(self):
        for path in ["lib/plugins/view/plugin_background_host.dart",
                     "integration_test/apple_plugin_activity_probe_test.dart",
                     "tool/perf_probe/apple_plugin_activity/run.py",
                     "tool/perf_probe/apple_plugin_activity/test_macos_controller.py",
                     ".github/workflows/apple-plugin-activity.yml"]:
            with self.subTest(path=path):
                self.assertEqual(decide([path])[:2], (True, True))

    def test_contract_inputs_skip_the_mac_jobs(self):
        for path in ["test/tool/perf_probe/perf_fixture_test.dart",
                     "integration_test/support/installed_plugin_completion.dart",
                     "tool/perf_probe/apple_plugin_activity/test_runner.py"]:
            with self.subTest(path=path):
                self.assertEqual(decide([path])[:2], (True, False))

    def test_unrelated_dependency_change_runs_nothing(self):
        head = lock(flutter_inappwebview_ios="1.2.0", sentry_flutter="9.30.1",
                    window_manager="0.5.0", markdown="7.3.1", googleapis="18.0.0")
        self.assertEqual(decide(["pubspec.lock", "pubspec.yaml", "lib/main.dart"], head),
                         (False, False, []))

    def test_native_hook_package_change_runs_every_job(self):
        base = lock(flutter_inappwebview_ios="1.2.0", sentry_flutter="9.30.1",
                    window_manager="0.5.0", markdown="7.3.0", googleapis="17.0.0",
                    opentype_shaper="0.1.0")
        head = base.replace('version: "0.1.0"', 'version: "0.2.0"')
        result = changes.decide({"pubspec.lock"}, WORKFLOW,
                                {"pubspec.lock": base, "pubspec.yaml": PUBSPEC}.__getitem__,
                                {"pubspec.lock": head, "pubspec.yaml": PUBSPEC}.__getitem__)
        self.assertEqual(result[:2], (True, True))

    def test_scenario_dependency_change_runs_every_job(self):
        for changed in [dict(flutter_inappwebview_ios="1.2.1"), dict(sentry_flutter="9.31.0"),
                        dict(window_manager=None), dict(pdfium_flutter="0.4.2")]:
            with self.subTest(changed=changed):
                packages = dict(flutter_inappwebview_ios="1.2.0", sentry_flutter="9.30.1",
                                window_manager="0.5.0", markdown="7.3.0", googleapis="17.0.0")
                packages.update(changed)
                head = lock(**{k: v for k, v in packages.items() if v is not None})
                contracts, apple, reasons = decide(["pubspec.lock"], head)
                self.assertEqual((contracts, apple), (True, True))
                self.assertIn(next(iter(changed)), reasons[0])

    def test_git_ref_change_counts_without_a_version_change(self):
        head = BASE_LOCK.replace(
            "  flutter_inappwebview_ios:\n    dependency: transitive\n",
            "  flutter_inappwebview_ios:\n    dependency: \"direct main\"\n")
        self.assertEqual(decide(["pubspec.lock"], head)[:2], (False, False))
        head = BASE_LOCK.replace("name: flutter_inappwebview_ios\n",
                                 "name: flutter_inappwebview_ios\n      ref: abc\n")
        self.assertEqual(decide(["pubspec.lock"], head)[:2], (True, True))

    def test_native_hook_settings_run_every_job(self):
        pubspec = PUBSPEC + "hooks:\n  user_defines:\n    otzaria_search_engine:\n      build_from_source: true\n"
        contracts, apple, reasons = decide(["pubspec.yaml"], head_pubspec=pubspec)
        self.assertEqual((contracts, apple), (True, True))
        self.assertEqual(reasons, ["native build hook settings in pubspec.yaml"])

    def test_file_moved_out_of_a_trigger_path_runs_every_job(self):
        import subprocess
        import tempfile
        with tempfile.TemporaryDirectory() as name:
            def run(*args):
                subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", *args],
                               cwd=name, check=True, capture_output=True)
            source = Path(name, "lib/plugins/services/runtime.dart")
            source.parent.mkdir(parents=True)
            source.write_text("".join(f"line {i}\n" for i in range(50)))
            run("init", "-q")
            run("add", ".")
            run("commit", "-qm", "base")
            Path(name, "lib/core").mkdir()
            run("mv", "lib/plugins/services/runtime.dart", "lib/core/runtime.dart")
            run("commit", "-qm", "move")
            files = changes.changed_files("HEAD^1", "HEAD", cwd=name)
        self.assertIn("lib/plugins/services/runtime.dart", files)
        self.assertEqual(decide(files)[:2], (True, True))

    def test_actual_lockfile_parses_scenario_packages(self):
        text = (Path(__file__).resolve().parents[3] / "pubspec.lock").read_text()
        packages = changes.lock_packages(text)
        self.assertIn("resolved-ref:", packages["flutter_inappwebview_ios"])
        self.assertNotIn("dependency:", packages["flutter_inappwebview_ios"])
        for name in ["flutter_inappwebview_ios", "sentry_flutter", "window_manager", "vm_service"]:
            self.assertIn(name, changes.scenario_packages(packages))
        self.assertNotIn("markdown", changes.scenario_packages(packages))


if __name__ == "__main__":
    unittest.main()
