// Generates the Torah page layouts from one source, the Or LaSofer tables in
// tool/tikkun_korim/vendor/or_lasofer_layouts.json:
//   lib/tools/tikkun_korim/data/torah_layouts.g.dart       methods and pages
//   lib/tools/tikkun_korim/data/torah_page_anchors.g.dart  each page's anchor
// Each page's first and last word is resolved against the Torah text.
//   flutter test tool/tikkun_korim/generate_torah_layouts_test.dart
// Set ANCHORS_OUT to a directory to also write a report of suspicious pages.
