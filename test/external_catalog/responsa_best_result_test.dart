import 'package:flutter_test/flutter_test.dart';
import 'package:otzaria/external_catalog/responsa/native/responsa_automation.dart';

/// ההפניה היא רק השאילתה שייצרה את הרשימה, והספר המבוקש הוא הכותרת: כשהחוליה
/// רחבה, דירוג לפי ההפניה בוחר שורה שגויה מרשימה שיש בה את הנכונה.
void main() {
  int pick(List<String> results, String ref, [String? expected]) =>
      ResponsaAutomation.bestResult(results, ref, expected);

  test('הכותרת המצופה מכריעה, לא ההפניה', () {
    // החוליה שנותחה, `על הש"ס ברכות`, מתאימה לשתי השורות.
    final results = [
      'שרידי אש על הש"ס ברכות',
      'בית הבחירה למאירי על הש"ס ברכות',
    ];
    expect(
      pick(results, 'על הש"ס ברכות', 'בית הבחירה למאירי על הש"ס ברכות'),
      1,
    );
  });

  test('חוליה רחבה שהרשימה שלה מכילה את הספר הנכון', () {
    final results = [
      'פסקי רי"ד מסכת ברכות',
      'פסקי רי"ד מסכת בבא קמא',
      'פסקי רי"ד מסכת מכות',
    ];
    expect(pick(results, 'רי"ד', 'רי"ד (פסקים) בבא קמא משניות'), 1);
  });

  test('בלי כותרת מצופה ההפניה מכריעה', () {
    final results = ['מהרש"א פסחים', 'מהרש"א בבא בתרא'];
    expect(pick(results, 'מהרש"א בבא בתרא'), 1);
  });

  test('בשוויון נשארת המוקדמת', () {
    final results = ['תוספות יום טוב שבת', 'תוספות יום טוב שבת'];
    expect(pick(results, 'תוספות יום טוב שבת', 'תוספות יום טוב שבת'), 0);
  });

  test('אף שורה אינה מתאימה — הראשונה', () {
    expect(pick(['אין כאן דבר', 'וגם לא כאן'], 'מהרש"א', 'מהרש"א פסחים'), 0);
  });

  test('ההסתייגות אינה מפריעה לדירוג', () {
    // `withoutQualifier` על הכותרת המצופה, כי הסוגריים הם מטא-דאטה של
    // הקטלוג ואינם מופיעים בשורות של התוכנה.
    final results = ['אוצר מדרשים (אייזנשטיין) היכלות', 'מדרש אחר לגמרי'];
    expect(pick(results, 'היכלות', "היכלות (עמ' 108-126)"), 0);
  });
}
