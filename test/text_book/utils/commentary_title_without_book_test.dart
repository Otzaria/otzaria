// השמטת שם הספר שכבר מופיע בכותרת הקבוצה מכותרת המקטע (issue #3599).
import 'package:flutter_test/flutter_test.dart';
import 'package:otzaria/text_book/utils/commentary_title_visibility.dart';

void main() {
  String shorten(String title, String group) =>
      commentaryTitleWithoutBook(displayTitle: title, groupBookTitle: group);

  test('שם הספר בכותרת הקבוצה מושמט, גם בגרשיים שונים', () {
    expect(shorten('רש"י על שופטים ו, ה', 'רש״י על שופטים'), 'ו, ה');
    expect(shorten('רש"י על שופטים ו, ח', 'רש"י על שופטים'), 'ו, ח');
  });

  test('פסיק אחרי שם הספר — הכתובת בלבד', () {
    expect(shorten('רש"י על בכורות, ג ב', 'רש"י על בכורות'), 'ג ב');
  });

  test('ניקוד בכותרת אינו מונע את הקיצור', () {
    expect(shorten('רַשִׁ"י על שופטים ו, ה', 'רש"י על שופטים'), 'ו, ה');
  });

  test('כותרת שאינה מתחילה בשם הספר — ללא שינוי', () {
    expect(
      shorten('תוספות בכורות, ג ב', 'רש"י על בכורות'),
      'תוספות בכורות, ג ב',
    );
  });

  test('מילה שרק מתחילה כמו שם הספר — ללא שינוי', () {
    expect(
      shorten('רש"י על שופטימ ו, ה', 'רש"י על שופט'),
      'רש"י על שופטימ ו, ה',
    );
  });

  test('כותרת שהיא שם הספר בלבד — ללא שינוי', () {
    expect(shorten('רש"י על שופטים', 'רש"י על שופטים'), 'רש"י על שופטים');
  });

  test('סיומת טווח מיד אחרי שם הספר — ללא שינוי', () {
    expect(
      shorten('רש"י על שופטים – ו, ח', 'רש"י על שופטים'),
      'רש"י על שופטים – ו, ח',
    );
  });

  test('טווח אחרי כתובת — נשמר במלואו אחרי הקיצור', () {
    expect(shorten('רש"י על בכורות, ג ב–ג', 'רש"י על בכורות'), 'ג ב–ג');
  });
}
