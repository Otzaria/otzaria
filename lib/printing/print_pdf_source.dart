import 'dart:io';
import 'dart:math';
import 'dart:typed_data';

import 'package:pdfrx/pdfrx.dart';

/// מקור PDF שנפתח מקובץ, או מבתים של מסמך שנוצר בזיכרון.
class PrintPdfSource {
  const PrintPdfSource.file(String path) : _path = path, _data = null;
  const PrintPdfSource.data(Uint8List data) : _data = data, _path = null;

  final String? _path;
  final Uint8List? _data;

  Future<Uint8List> readBytes() async =>
      _data ?? await File(_path!).readAsBytes();

  Future<PdfDocument> open({bool useProgressiveLoading = false}) {
    final path = _path;
    if (path != null) {
      return PdfDocument.openFile(
        path,
        useProgressiveLoading: useProgressiveLoading,
      );
    }
    final bytes = _data!;
    // Generated bytes must stay on the memory-loading path: native read
    // callbacks can deadlock when a previous document is being closed.
    return PdfDocument.openCustom(
      read: (buffer, position, size) {
        final count = min(size, bytes.length - position);
        if (count <= 0) return 0;
        buffer.setRange(0, count, bytes, position);
        return count;
      },
      fileSize: bytes.length,
      sourceName: 'print-memory-${identityHashCode(bytes)}',
      maxSizeToCacheOnMemory: bytes.length,
      useProgressiveLoading: useProgressiveLoading,
    );
  }
}
