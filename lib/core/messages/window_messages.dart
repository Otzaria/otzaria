/// ריכוז כל ההודעות למשתמש של ריבוי החלונות.
///
/// כל טקסט שמוצג למשתמש בפתיחת חלון, בהעברת כרטיסיה בין חלונות ובגרירה
/// ביניהם מוגדר כאן בלבד — אין לכתוב מחרוזות כאלה בקבצי הפיצ'רים.
abstract class WindowMessages {
  // ── העברת כרטיסיה בין חלונות ───────────────────────────────────────────

  static const String cannotTransferTab =
      'לא ניתן להעביר את הכרטיסיה הזו לחלון אחר.';

  static const String cannotTransferLastTab =
      'זו הכרטיסיה האחרונה בחלון. העברתה תשאיר חלון ריק.';

  static const String transferFailed = 'העברת הכרטיסיה לחלון נכשלה.';

  /// היעד לא ענה בזמן. הכרטיסיה **לא** הוסרה כאן, אך ייתכן שנקלטה גם שם.
  static const String transferUnconfirmed =
      'החלון היעד לא השיב בזמן. הכרטיסיה נשארה כאן — בדוק אם היא נפתחה גם שם.';

  // ── פתיחת חלון ─────────────────────────────────────────────────────────

  static const String openWindowFailed = 'פתיחת החלון נכשלה.';

  static String windowLimitReached(int max) =>
      'אפשר לפתוח עד $max חלונות. סגור חלון כדי לפתוח חדש.';

  /// כרטיסיה שהועברה לחלון חדש אך לא נפתחה שם.
  ///
  /// ⚠️ **בלי הבטחה על היסטוריה.** הנוסח הקודם הצהיר "היא נשמרה
  /// בהיסטוריה", ואין במסלול הזה שום קוד שמוסיף להיסטוריה: החלון המקורי
  /// עשה `RemoveTab` בלבד. המסלול אמור להיות בלתי-נגיש
  /// ([MultiWindowService.canTransfer] בודק בדיוק את מסע ההלוך-ושוב הזה),
  /// וההודעה היא רשת ביטחון — ולכן היא חייבת להיות מדויקת.
  static const String transferredTabDecodeFailed =
      'הכרטיסיה לא נפתחה בחלון החדש. יש לפתוח אותה שוב מהספרייה.';

  // ── יכולות שאינן זמינות בחלון משני ─────────────────────────────────────

  /// ⚠️ ההדפסה נשענת על פלאגין שאינו נרשם בחלונות משניים (החלטה מתועדת
  /// ב-`docs/multi-window.md`), ובלי הודעה הלחיצה פשוט לא עשתה כלום.
  static const String printOnlyInMainWindow =
      'הדפסה אפשרית רק בחלון הראשי של אוצריא. עבור לחלון הראשי ונסה שוב.';

  /// ⚠️ Tantivy נועל את ה-writer בלעדית, והחלון הראשון מחזיק את הנעילה.
  static const String indexingOnlyInMainWindow =
      'בניית אינדקס החיפוש אפשרית רק בחלון הראשי של אוצריא. עבור לחלון '
      'הראשי ונסה שוב.';

  /// כרטיסיית חלון אחר בתת-התפריט "העבר לחלון קיים".
  static String peerWithTabs(String title, int tabCount) => switch (tabCount) {
    1 => '$title (כרטיסיה אחת)',
    2 => '$title (שתי כרטיסיות)',
    _ => '$title ($tabCount כרטיסיות)',
  };
}
