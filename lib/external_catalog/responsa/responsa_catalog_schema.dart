/// גרסת הסכמה של `responsa_catalog.db`.
///
/// * **1** — הכותרת היא שם הצומת בעץ, וההפניה נבנתה ממנו כפי שהוא.
/// * **2** — הכותרת היא השם המלא של הספר (`הון עשיר אבות` ולא `אבות`),
///   ההפניות נגזרות משמות ליבה נקיים מעטיפת הסוגריים של המאגר, ולכל
///   ספר נשמר סולם הפניות חלופיות.
/// * **3** — מבנה הספר נקרא מ-`lParam` של הצומת ולא מניחוש לפי שמות:
///   שם החיבור, שם המחבר או הסדרה שמעליו, והיחידות שמתחתיו. צמתי
///   קטגוריה שסווגו כספרים סולקו, ונשמר נתיב הקטגוריה המלא לשיוך
///   לקטגוריות אוצריא.
/// * **4** — נתיב הקטגוריה כולל את הרכיב שמעל החיבור, שהוא גם מדף
///   (`ספרות חז"ל > משנה` ולא `ספרות חז"ל` לבדו), וחיבור שהעץ מציג
///   בשני נתיבים נשמר פעם אחת. קטלוג בסכמה 3 שייך את כל המשנה,
///   התוספתא והבבלי לתלמוד בבלי, והכיל 63 רשומות שאינן נפתחות.
/// * **5** — לכל ספר נשמרים `author`, `pub_place`, `pub_date` ו-`edition`
///   מתוך "רשימת הספרים והמהדורות" שבקובץ העזרה של ההתקנה. עד לסכמה 4
///   ספרי בר אילן היו היחידים בספרייה בלי שם מחבר ובלי פרטי הדפסה.
/// * **6** — המחבר נלקח מטבלת המחברים שבארכיון הספרים, לפי מזהה החיבור,
///   והביבליוגרפיה היא נסיגה בלבד. בסכמה 5 היה מחבר ל-994 מתוך 8,402
///   ספרים, וחלקם שגויים — `ר"ש` על זרעים קיבל את שמו של רש"י.
///
/// הקבוע יושב בקובץ נפרד כדי ששכבת הבנייה (שאינה מכירה את אוצריא)
/// ושכבת הקריאה (שאינה מכירה את Win32) יוכלו שתיהן להשוות אליו.
const int responsaCatalogSchemaVersion = 6;
